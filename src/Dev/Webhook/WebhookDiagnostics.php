<?php

namespace Snorky22\ApiForge\Dev\Webhook;

use Psr\Container\ContainerInterface;
use Snorky22\ApiForge\Core\Webhook\AbstractWebhookConsumer;
use Snorky22\ApiForge\Dev\Doctor\Check;
use Symfony\Contracts\HttpClient\Exception\TransportExceptionInterface;

/**
 * Checks the webhook chain of the application for an API, from the URL to the consumer, and reports what
 * breaks it: routes not imported, missing secret, no consumer, events queued without a worker…
 */
final class WebhookDiagnostics
{
    /** Recent deliveries looked at */
    private const RECENT = 10;

    /**
     * @param ?ContainerInterface $consumers the registered RemoteEvent consumers, by type
     * @param ?DeliveryInbox      $inbox     the deliveries received, when the inbox is enabled
     */
    public function __construct(
        private readonly WebhookSender $sender,
        private readonly ?ContainerInterface $consumers = null,
        private readonly ?DeliveryInbox $inbox = null,
    ) {
    }

    /**
     * What the inbox says about the last deliveries of the provider (not the simulated ones).
     *
     * @return list<Check>
     */
    public function deliveries(string $type): array
    {
        if (null === $this->inbox) {
            return [];
        }
        $deliveries = array_values(array_filter($this->inbox->latest($type, 50), static fn (array $delivery) => 'provider' === $delivery['origin']));
        if ([] === $deliveries) {
            return [Check::warning('No delivery from the provider recorded yet (api-forge:webhook:inbox): nothing has reached the endpoint.')];
        }

        $last = $deliveries[0];
        $checks = [Check::ok(\sprintf('Last delivery from the provider: %s, %s, %s.', $last['received_at'], $last['event'] ?? '?', $last['status']))];
        $recent = \array_slice($deliveries, 0, self::RECENT);
        $failures = array_values(array_filter($recent, static fn (array $delivery) => \in_array($delivery['status'], [DeliveryInbox::REJECTED, DeliveryInbox::FAILED, DeliveryInbox::UNKNOWN_TYPE], true)));
        if ([] !== $failures) {
            $checks[] = Check::warning(\sprintf('%d of the last %d deliveries were not consumed; the latest: %s %s (%s): %s. See api-forge:webhook:inbox --show=%s, replay with api-forge:webhook:replay.', \count($failures), \count($recent), $failures[0]['event'] ?? '?', $failures[0]['status'], $failures[0]['received_at'], rtrim($failures[0]['reason'] ?? 'no reason', '.'), $failures[0]['id']));
        }

        return $checks;
    }

    /**
     * Which events the application's consumer handles: the methods of the generated base consumer it overrides.
     *
     * @return ?array{handled: list<string>, events: list<string>} null when the consumer isn't generated by api-forge
     */
    public function coverage(string $type): ?array
    {
        $consumer = $this->consumers?->has($type) ? $this->consumers->get($type) : null;
        if (!$consumer instanceof AbstractWebhookConsumer) {
            return null;
        }

        $handlers = new \ReflectionClassConstant($consumer, 'HANDLERS');
        $base = $handlers->getDeclaringClass()->getName();
        $events = $handled = [];
        foreach ($handlers->getValue() as $event => $method) {
            $events[] = (string) $event;
            if ((new \ReflectionMethod($consumer, $method))->getDeclaringClass()->getName() !== $base) {
                $handled[] = (string) $event;
            }
        }

        return ['handled' => $handled, 'events' => $events];
    }

    /**
     * Checks the webhooks registered at the provider: one must send to the endpoint, with the events the consumer
     * handles.
     *
     * @param list<array{id: ?string, url: string, events: ?list<string>}> $registrations
     * @param list<string>                                                 $requiredEvents events whose absence is an error, not a warning
     *
     * @return array{list<Check>, list<string>} the checks, and the URLs that point to the endpoint (to ping)
     */
    public function registrations(string $type, array $registrations, array $requiredEvents = []): array
    {
        $path = rtrim((string) parse_url($this->sender->url($type), \PHP_URL_PATH), '/');
        $handled = $this->coverage($type)['handled'] ?? null;
        $checks = $urls = [];
        foreach ($registrations as $registration) {
            $label = \sprintf('Webhook %s(%s)', null !== $registration['id'] ? $registration['id'].' ' : '', $registration['url']);
            if (rtrim((string) parse_url($registration['url'], \PHP_URL_PATH), '/') !== $path) {
                $checks[] = Check::warning(\sprintf('%s does not send to the endpoint path %s: its deliveries never reach the application.', $label, $path));
                continue;
            }

            $urls[] = $registration['url'];
            $checks[] = Check::ok(\sprintf('%s sends to the endpoint.', $label));
            if (null === $registration['events']) {
                continue;
            }
            if ([] !== $missing = array_values(array_diff($requiredEvents, $registration['events']))) {
                $checks[] = Check::error(\sprintf('%s does not send %s, required.', $label, implode(', ', $missing)));
            }
            if (null !== $handled && [] !== $missing = array_values(array_diff($handled, $registration['events'], $requiredEvents))) {
                $checks[] = Check::warning(\sprintf('%s does not send %s: the consumer handles them, they never arrive.', $label, implode(', ', $missing)));
            }
        }
        if ([] === $urls) {
            $checks[] = Check::error(\sprintf('No webhook registered at the provider sends to %s: register https://<public host>%1$s, with the signing secret of the webhook routing.', $path));
        }

        return [$checks, $urls];
    }

    /**
     * @return list<Check>
     */
    public function check(string $type): array
    {
        $checks = [];
        try {
            $url = $this->sender->url($type);
            $checks[] = Check::ok(\sprintf('Endpoint: %s (path %s)', $url, parse_url($url, \PHP_URL_PATH)));
        } catch (\InvalidArgumentException $e) {
            return [Check::error($e->getMessage())];
        }

        try {
            $this->sender->headers($type, '{}');
            $checks[] = Check::ok('Request parser routed, signing secret set.');
        } catch (\InvalidArgumentException $e) {
            $checks[] = Check::error($e->getMessage());
        }

        $checks[] = $this->consumers?->has($type)
            ? Check::ok(\sprintf('Consumer registered (#[AsRemoteEventConsumer(\'%s\')]).', $type))
            : Check::error(\sprintf('No consumer registered with #[AsRemoteEventConsumer(\'%s\')]: deliveries are accepted, then fail.', $type));
        if (null !== $coverage = $this->coverage($type)) {
            $checks[] = Check::ok(\sprintf('The consumer handles %d of the %d events%s.', \count($coverage['handled']), \count($coverage['events']), [] !== $coverage['handled'] ? ': '.implode(', ', $coverage['handled']) : ''));
        }

        array_push($checks, ...$this->deliveries($type));

        $async = $this->sender->asyncTransports($type);
        $checks[] = [] === $async
            ? Check::ok('Events consumed during the request (no asynchronous transport).')
            : Check::warning(\sprintf('Events queued on the "%s" transport: a worker must run (messenger:consume %s), or they are never consumed.', implode('", "', $async), implode(' ', $async)));

        return $checks;
    }

    /**
     * Sends a signed ping to a public URL (tunnel, proxy) and reports whether it reaches the endpoint.
     */
    public function ping(string $type, string $url): Check
    {
        try {
            [$status, $body] = $this->sender->ping($type, $url);
        } catch (TransportExceptionInterface $e) {
            return Check::error(\sprintf('%s is unreachable (tunnel down? wrong host?): %s', $url, $e->getMessage()));
        } catch (\InvalidArgumentException $e) {
            return Check::error($e->getMessage());
        }

        $path = parse_url($this->sender->url($type), \PHP_URL_PATH);
        $excerpt = mb_strimwidth(trim(strip_tags($body)), 0, 160, '…');

        // The webhook endpoint answers 202: another success status comes from another page (a path is missing)
        return match (true) {
            202 === $status => Check::ok(\sprintf('%s reaches the endpoint, signed with the same secret (HTTP 202).', $url)),
            $status >= 200 && $status < 300 => Check::error(\sprintf('%s answers HTTP %d, not the webhook endpoint (202): the path should be %s.', $url, $status, $path)),
            404 === $status => Check::error(\sprintf('%s answers 404: wrong path (the endpoint is %s), or the tunnel is offline. %s', $url, $path, $excerpt)),
            406 === $status => Check::error(\sprintf('%s rejects the signature (HTTP 406): the server behind the URL has another secret, or is another application. %s', $url, $excerpt)),
            default => Check::error(\sprintf('%s answers HTTP %d: %s', $url, $status, $excerpt)),
        };
    }
}
