<?php

namespace Snorky22\ApiForge\Dev\Api\Generator;

use Snorky22\ApiForge\Dev\Api\Descriptor\ApiDefinition;
use Snorky22\ApiForge\Dev\Api\Naming;
use Symfony\Component\Yaml\Yaml;

/**
 * Generates the Symfony services of an API from its validated descriptors, with the default paths:
 *
 * - one class per resource, src/Api/<Namespace>/Generated/Resource/<Resource>.php
 * - an entry point with one property per resource, src/Api/<Namespace>/Generated/<Namespace>Api.php
 * - for webhooks: a request parser, the event constants and payload types, and a base consumer,
 *   in src/Api/<Namespace>/Generated/Webhook/
 * - the scoped HTTP client and the webhook routing, config/packages/api_<name>.yaml
 *
 * The output only depends on the descriptors, so regenerating unchanged descriptors gives identical files.
 */
final class ServiceGenerator
{
    public const MARKER = 'Generated by api-forge:generate';
    private const LINE_LENGTH = 120;

    /**
     * @param string $namespace PHP namespace of the generated code, the API namespace is appended to it
     * @param string $sourceDir directory of this namespace, relative to the project directory
     * @param string $configDir directory of the generated configuration, relative to the project directory
     */
    public function __construct(
        private readonly string $namespace = 'App\\Api',
        private readonly string $sourceDir = 'src/Api',
        private readonly string $configDir = 'config/packages',
    ) {
    }

    /**
     * Directory of the generated code of an API, relative to the project directory.
     */
    public function generatedDirectory(ApiDefinition $definition): string
    {
        return trim($this->sourceDir, '/').'/'.$definition->namespace.'/Generated';
    }

    /**
     * @param string $descriptorDir descriptor directory as shown in the generated file headers
     *
     * @return array<string, string> file path relative to the project directory => content
     */
    public function generate(ApiDefinition $definition, string $descriptorDir): array
    {
        $directory = $this->generatedDirectory($definition);
        $files = [];
        foreach ($definition->resources as $name => $resource) {
            $files[$directory.'/Resource/'.Naming::className($name).'.php'] = $this->resourceClass($definition, $name, $resource, $descriptorDir.'/'.$name.'.yaml');
        }
        $files[$directory.'/'.$definition->namespace.'Api.php'] = $this->entryPoint($definition, $descriptorDir);
        $files[$directory.'/'.$definition->namespace.'Doctor.php'] = $this->doctor($definition, $descriptorDir.'/_api.yaml');
        if (null !== $definition->webhooks) {
            $source = $descriptorDir.'/_webhooks.yaml';
            $files[$directory.'/Webhook/'.$definition->namespace.'RequestParser.php'] = $this->requestParser($definition, $source);
            $files[$directory.'/Webhook/'.$definition->namespace.'WebhookEvents.php'] = $this->webhookEvents($definition, $source);
            $files[$directory.'/Webhook/Abstract'.$definition->namespace.'WebhookConsumer.php'] = $this->webhookConsumer($definition, $source);
        }
        $files[trim($this->configDir, '/').'/api_'.$definition->name.'.yaml'] = $this->clientConfig($definition, $descriptorDir);

        return $files;
    }

    public static function serviceId(string $apiName): string
    {
        return $apiName.'.client';
    }

    private function resourceClass(ApiDefinition $definition, string $name, array $resource, string $source): string
    {
        $jsonApi = 'jsonapi' === $definition->api['format'];
        $class = Naming::className($name);
        $alias = isset($resource['object']) ? Naming::aliasName($resource['type'] ?? $name) : null;
        $baseClass = $jsonApi ? 'AbstractJsonApiResource' : 'AbstractResource';

        $doc = [\sprintf('"%s" resource of the %s API%s.', $name, $definition->namespace, null !== $resource['type'] ? \sprintf(' (JSON:API type "%s")', $resource['type']) : '')];
        if (null !== $alias) {
            array_push($doc, '', '@phpstan-type '.$alias.' '.$resource['object']['shape']);
        }

        $members = [];
        if ($jsonApi && null !== $resource['type']) {
            $members[] = '    protected const TYPE = '.$this->export($resource['type']).';';
        }
        $members[] = <<<PHP
                public function __construct(#[Autowire(service: {$this->export(self::serviceId($definition->name))})] HttpClientInterface \$client)
                {
                    parent::__construct(\$client);
                }
            PHP;

        foreach ($resource['operations'] as $operationName => $operation) {
            $members[] = $this->method((string) $operationName, $operation, $resource, $alias, $jsonApi);
            if ($jsonApi && 'list' === $operationName && 'list' === ($operation['response']['data'] ?? null)) {
                $members[] = $this->method('iterate', $operation, $resource, $alias, $jsonApi, true);
            }
        }

        return $this->header($source)
            .'namespace '.$this->apiNamespace($definition)."\\Resource;\n\n"
            ."use Snorky22\\ApiForge\\Core\\{$baseClass};\n"
            ."use Symfony\\Component\\DependencyInjection\\Attribute\\Autowire;\n"
            ."use Symfony\\Contracts\\HttpClient\\HttpClientInterface;\n\n"
            .$this->docBlock($doc, '')
            ."class {$class} extends {$baseClass}\n{\n"
            .implode("\n\n", $members)
            ."\n}\n";
    }

    /**
     * @param bool $iterate generate the iterator over all pages of a "list" operation
     */
    private function method(string $name, array $operation, array $resource, ?string $alias, bool $jsonApi, bool $iterate = false): string
    {
        $required = $optional = [];
        $doc = $iterate
            ? [\sprintf('Iterates over all the "%s" resources, following the pagination links.', $resource['resource']), '', $operation['method'].' '.$operation['path']]
            : [$operation['method'].' '.$operation['path']];
        $paramDoc = [];

        $pathArguments = [];
        foreach ($operation['parameters'] as $parameter => $info) {
            $required[] = 'int|string $'.$parameter;
            $paramDoc[] = ['int|string', $parameter, $this->describe($info['description'], $info['example'])];
            $pathArguments[] = $this->export((string) $parameter).' => $'.$parameter;
        }

        $queryArguments = [];
        foreach ($operation['query'] as $queryName => $info) {
            $variable = Naming::variableName((string) $queryName);
            $type = ($info['required'] ? '' : '?').$info['type'];
            if ($info['required']) {
                $required[] = $type.' $'.$variable;
            } else {
                $optional[] = $type.' $'.$variable.' = null';
            }
            $paramDoc[] = [$type, $variable, $this->describe($info['description'], $info['example'], (string) $queryName)];
            $queryArguments[] = $this->export((string) $queryName).' => $'.$variable;
        }

        $body = [];
        if (isset($operation['body']) && !$iterate) {
            if (isset($operation['body']['attributes'])) {
                $required[] = 'array $attributes';
                $paramDoc[] = [$operation['body']['attributes']['shape'], 'attributes', ''];
                $documentArguments = ['$attributes'];
                if ([] !== $relationships = $operation['body']['relationships']) {
                    array_unshift($optional, 'array $relationships = []');
                    $paramDoc[] = [$this->relationshipsType($relationships), 'relationships', 'related resource ids'];
                    array_push($documentArguments, '$relationships', $this->exportMap($relationships));
                }
                // JSON:API updates (and actions like "POST orders/{id}/refund", body.id) identify the resource
                // in the document too: it is the last path parameter.
                if (($operation['body']['id'] ?? \in_array($operation['method'], ['PATCH', 'PUT'], true)) && [] !== $operation['parameters']) {
                    $documentArguments[] = 'id: $'.array_key_last($operation['parameters']);
                }
                $body = ['json' => '$this->document('.implode(', ', $documentArguments).')'];
            } elseif (isset($operation['body']['shape'])) {
                $required[] = 'array $body';
                $paramDoc[] = [$operation['body']['shape'], 'body', ''];
                $body = ['json' => '$body'];
            } else {
                $required[] = 'string $body';
                $paramDoc[] = ['string', 'body', 'raw request body'];
                $body = ['body' => '$body'];
            }
        }

        $optional[] = 'array $query = []';
        $paramDoc[] = ['array<string, mixed>', 'query', 'additional query parameters'];

        $doc[] = '';
        foreach ($paramDoc as [$type, $variable, $description]) {
            $doc[] = rtrim('@param '.$type.' $'.$variable.' '.$description);
        }
        $doc[] = '';
        $doc[] = '@return '.($iterate ? '\\Generator<int, '.($alias ?? 'array<string, mixed>').'>' : $this->returnType($operation, $alias));
        if (!$iterate) {
            $doc[] = '';
            $doc[] = '@throws \\Snorky22\\ApiForge\\Core\\ApiException';
        }

        $query = [] === $queryArguments ? '$query' : '$query + ['.implode(', ', $queryArguments).']';
        $parameters = '['.implode(', ', $pathArguments).']';
        if ($iterate) {
            $call = $this->call('$this->paginate', [$this->export($operation['path']), $parameters, $query]);
        } else {
            $arguments = [$this->export($operation['method']), $this->export($operation['path'])];
            if ([] !== $pathArguments) {
                $arguments[] = $parameters;
            }
            $arguments[] = 'query: '.$query;
            foreach ($body as $key => $value) {
                $arguments[] = $key.': '.$value;
            }
            if ([] !== $operation['headers']) {
                $arguments[] = 'headers: '.$this->exportMap($operation['headers']);
            }
            $call = $this->call('$this->request', $arguments);
        }

        return $this->docBlock($doc, '    ')
            .'    public function '.$name.$this->signature(array_merge($required, $optional)).': '.($iterate ? '\\Generator' : 'array')."\n"
            ."    {\n"
            .'        return '.$call.";\n"
            .'    }';
    }

    private function returnType(array $operation, ?string $alias): string
    {
        if (isset($operation['response']['shape'])) {
            return trim($operation['response']['shape']);
        }
        if (!isset($operation['response']['data'])) {
            return 'array<mixed>';
        }

        $object = $alias ?? 'array<string, mixed>';

        return 'list' === $operation['response']['data']
            ? "array{\n    data: list<{$object}>,\n    links?: array<string, ?string>,\n    meta?: array<string, mixed>,\n    included?: list<array<string, mixed>>,\n}"
            : "array{\n    data: {$object},\n    links?: array<string, string>,\n    meta?: array<string, mixed>,\n    included?: list<array<string, mixed>>,\n}";
    }

    /**
     * @param array<string, string> $relationships
     */
    private function relationshipsType(array $relationships): string
    {
        $entries = [];
        foreach ($relationships as $name => $type) {
            $key = Naming::isIdentifier($name) ? $name : $this->export($name);
            $entries[] = $key.'?: '.(str_ends_with($type, '[]') ? 'list<int|string>' : 'int|string|null');
        }

        return 'array{'.implode(', ', $entries).'}';
    }

    /**
     * The doctor of the API (api-forge:doctor): its environment variables, and the probe of doctor.probe.
     */
    private function doctor(ApiDefinition $definition, string $source): string
    {
        $env = [];
        if (isset($definition->api['auth'])) {
            $env[$definition->api['auth']['env']] = 'credentials';
        }
        if (null !== $definition->webhooks) {
            $env[$definition->webhooks['signature']['env']] = 'webhook signing secret';
        }

        $arguments = [];
        $parentArguments = [];
        $usesAutowire = false;
        foreach (array_keys($env) as $i => $name) {
            $arguments[] = "        #[Autowire('%env({$name})%')] #[\\SensitiveParameter] string \$env{$i},";
            $parentArguments[] = $this->export($name).' => $env'.$i;
            $usesAutowire = true;
        }

        $probe = $definition->api['doctor']['probe'] ?? null;
        $probeMethod = '';
        $contract = null;
        if (null !== $probe) {
            [$resource, $operationName] = explode('.', $probe, 2);
            $operation = $definition->resources[$resource]['operations'][$operationName];
            array_unshift($arguments, '        private readonly Resource\\'.Naming::className($resource).' $probeResource,');
            $callArguments = [];
            foreach (array_keys($operation['parameters']) as $parameter) {
                $callArguments[] = $this->doctorValue((string) $definition->api['doctor']['parameters'][$parameter], 'probe'.ucfirst(Naming::variableName((string) $parameter)), $arguments, $usesAutowire);
            }
            $probeMethod = "\n    protected function probe(): array\n    {\n        return \$this->probeResource->{$operationName}(".implode(', ', $callArguments).");\n    }\n";

            // The contract: the shape of the response, or of the resource objects of a JSON:API response
            if (isset($operation['response']['data'], $definition->resources[$resource]['object'])) {
                $contract = [$definition->resources[$resource]['object']['shape'], 'data', 'list' === $operation['response']['data']];
            } elseif (isset($operation['response']['shape'])) {
                $contract = [$operation['response']['shape'], null, false];
            }
        }

        // The webhooks registered at the provider (registration in _webhooks.yaml)
        $registrationMethod = '';
        if (null !== $registration = $definition->webhooks['registration'] ?? null) {
            [$resource, $operationName] = explode('.', $registration['operation'], 2);
            $operation = $definition->resources[$resource]['operations'][$operationName];
            $arguments[] = '        private readonly Resource\\'.Naming::className($resource).' $registrationResource,';
            $callArguments = [];
            foreach (array_keys($operation['parameters']) as $parameter) {
                $callArguments[] = $this->doctorValue((string) $registration['parameters'][$parameter], 'registration'.ucfirst(Naming::variableName((string) $parameter)), $arguments, $usesAutowire);
            }
            $query = [];
            foreach ($registration['query'] as $name => $value) {
                $query[] = $this->export((string) $name).' => '.$this->doctorValue((string) $value, 'registration'.ucfirst(Naming::variableName(preg_replace('/\W+/', '_', (string) $name))), $arguments, $usesAutowire);
            }
            if ([] !== $query) {
                $callArguments[] = 'query: ['.implode(', ', $query).']';
            }
            $items = $registration['items'] ?? ('jsonapi' === $definition->api['format'] ? 'data' : null);
            $export = fn (?string $value) => null !== $value ? $this->export($value) : 'null';
            $registrationMethod = "\n    public function registeredWebhooks(): array\n    {\n"
                ."        \$response = \$this->registrationResource->{$operationName}(".implode(', ', $callArguments).");\n\n"
                .'        return $this->registrations($response, '.$export($items).', '.$this->export($registration['url']).', '.$export($registration['events']).', '.$export($registration['id']).");\n    }\n";
        }

        $constructor = '';
        if ([] !== $arguments) {
            $constructor = "\n    public function __construct(\n".implode("\n", $arguments)."\n    ) {\n"
                .'        parent::__construct(['.implode(', ', $parentArguments)."]);\n    }\n";
        }

        $envConstant = [] === $env ? '[]' : "[\n".implode('', array_map(fn ($name, $role) => '        '.$this->export($name).' => '.$this->export($role).",\n", array_keys($env), $env)).'    ]';

        return $this->header($source)
            .'namespace '.$this->apiNamespace($definition).";\n\n"
            ."use Snorky22\\ApiForge\\Dev\\Doctor\\AbstractApiDoctor;\n"
            .($usesAutowire ? "use Symfony\\Component\\DependencyInjection\\Attribute\\Autowire;\n" : '')
            ."\n/**\n * Doctor of the {$definition->namespace} API: configuration, reachability, credentials\n * (php bin/console api-forge:doctor {$definition->name}).\n */\n"
            ."final class {$definition->namespace}Doctor extends AbstractApiDoctor\n{\n"
            .'    public const API = '.$this->export($definition->name).";\n"
            .'    protected const BASE_URI = '.$this->export($definition->api['base_uri']).";\n"
            .'    protected const ENV = '.$envConstant.";\n"
            .'    protected const PROBE = '.(null !== $probe ? $this->export($probe) : 'null').";\n"
            .(null !== $contract ? '    protected const PROBE_SHAPE = '.$this->export($contract[0]).";\n"
                .'    protected const PROBE_PATH = '.(null !== $contract[1] ? $this->export($contract[1]) : 'null').";\n"
                .'    protected const PROBE_LIST = '.($contract[2] ? 'true' : 'false').";\n" : '')
            .$constructor
            .$probeMethod
            .$registrationMethod
            ."}\n";
    }

    /**
     * A value of a doctor call: a container parameter or environment variable ("%...%") is injected through the
     * constructor, other values are literals.
     *
     * @param list<string> $arguments the constructor arguments, completed
     *
     * @return string the PHP expression of the value
     */
    private function doctorValue(string $value, string $variable, array &$arguments, bool &$usesAutowire): string
    {
        if (!preg_match('/^%(env\([^)]+\)|[\w.]+)%$/', $value)) {
            return $this->export($value);
        }
        $arguments[] = '        #[Autowire('.$this->export($value).')] private readonly string $'.$variable.',';
        $usesAutowire = true;

        return '$this->'.$variable;
    }

    private function entryPoint(ApiDefinition $definition, string $source): string
    {
        $properties = [];
        foreach (array_keys($definition->resources) as $name) {
            $properties[] = '        public readonly Resource\\'.Naming::className($name).' $'.Naming::variableName($name).',';
        }

        return $this->header($source)
            .'namespace '.$this->apiNamespace($definition).";\n\n"
            ."/**\n * Entry point of the {$definition->namespace} API, with one property per resource.\n */\n"
            ."final class {$definition->namespace}Api\n{\n"
            ."    public function __construct(\n"
            .implode("\n", $properties)."\n"
            ."    ) {\n"
            ."    }\n"
            ."}\n";
    }

    private function clientConfig(ApiDefinition $definition, string $source): string
    {
        $api = $definition->api;
        $client = ['base_uri' => $api['base_uri']];
        // "%" starts a container parameter: literal ones are doubled.
        $headers = array_map(static fn (string $value) => str_replace('%', '%%', $value), $api['headers']);

        $parameters = [];
        if (isset($api['auth'])) {
            $env = '%env('.$api['auth']['env'].')%';
            $parameters['env('.$api['auth']['env'].')'] = '';
            match ($api['auth']['type']) {
                'bearer' => $client['auth_bearer'] = $env,
                'basic' => $client['auth_basic'] = $env,
                'header' => $headers[$api['auth']['header']] = $env,
            };
        }
        if ([] !== $headers) {
            $client['headers'] = $headers;
        }

        $framework = ['http_client' => ['scoped_clients' => [self::serviceId($definition->name) => $client]]];
        if (null !== $webhooks = $definition->webhooks) {
            $env = $webhooks['signature']['env'];
            $parameters['env('.$env.')'] = '';
            $framework['webhook']['routing'][$definition->name] = [
                'service' => $this->webhookNamespace($definition).'\\'.$definition->namespace.'RequestParser',
                'secret' => '%env('.$env.')%',
            ];
        }

        $config = ([] !== $parameters ? ['parameters' => $parameters] : []) + ['framework' => $framework];

        return '# '.self::MARKER." from {$source}.\n# Do not edit: changes are lost on regeneration. Edit the descriptor instead.\n\n"
            .Yaml::dump($config, 10, 4);
    }

    private function requestParser(ApiDefinition $definition, string $source): string
    {
        $webhooks = $definition->webhooks;
        $constants = [
            'SIGNATURE_HEADER' => $webhooks['signature']['header'],
            'SIGNATURE_ALGORITHM' => $webhooks['signature']['algorithm'],
            'SIGNATURE_ENCODING' => $webhooks['signature']['encoding'],
            'SIGNATURE_PREFIX' => $webhooks['signature']['prefix'],
            'EVENT_NAME_PATH' => $webhooks['event_name']['path'],
            'EVENT_NAME_HEADER' => $webhooks['event_name']['header'],
            'EVENT_ID_PATH' => $webhooks['event_id']['path'] ?? null,
            'EVENT_ID_HEADER' => $webhooks['event_id']['header'] ?? null,
        ];
        $lines = [];
        foreach ($constants as $name => $value) {
            $lines[] = '    protected const '.$name.' = '.(null === $value ? 'null' : $this->export($value)).';';
        }

        return $this->header($source)
            .'namespace '.$this->webhookNamespace($definition).";\n\n"
            ."use Snorky22\\ApiForge\\Core\\Webhook\\AbstractSignedRequestParser;\n\n"
            ."/**\n * Request parser of the {$definition->namespace} webhooks, received on /webhook/{$definition->name}.\n */\n"
            ."class {$definition->namespace}RequestParser extends AbstractSignedRequestParser\n{\n"
            .implode("\n", $lines)."\n"
            ."}\n";
    }

    private function webhookEvents(ApiDefinition $definition, string $source): string
    {
        $webhooks = $definition->webhooks;
        $jsonApi = 'jsonapi' === $definition->api['format'];

        $doc = [\sprintf('Webhook events of the %s API, and the types of their payloads.', $definition->namespace), ''];
        $imports = [];
        foreach ($webhooks['events'] as $event) {
            $resource = $event['resource'] ?? null;
            if (null !== $resource && null === $event['shape'] && isset($definition->resources[$resource]['object'])) {
                $alias = Naming::aliasName($definition->resources[$resource]['type'] ?? $resource);
                $imports[$alias] = '@phpstan-import-type '.$alias.' from \\'.$this->apiNamespace($definition).'\\Resource\\'.Naming::className($resource);
            }
        }
        array_push($doc, ...array_values($imports));
        if ($jsonApi) {
            $doc[] = '@phpstan-type WebhookMeta '.trim($webhooks['meta']['shape'] ?? 'array<string, mixed>');
        }

        $constants = [];
        $all = [];
        foreach ($webhooks['events'] as $name => $event) {
            $name = (string) $name;
            $doc[] = '@phpstan-type '.$this->payloadAlias($name).' '.$this->payloadType($definition, $event, $imports);
            $constant = Naming::constantName($name);
            $constants[] = (null !== $event['description'] ? $this->docBlock([$this->description($event['description'])], '    ') : '')
                .'    public const '.$constant.' = '.$this->export($name).';';
            $all[] = '        self::'.$constant.',';
        }
        $constants[] = "    /** All the documented events. */\n    public const ALL = [\n".implode("\n", $all)."\n    ];";

        return $this->header($source)
            .'namespace '.$this->webhookNamespace($definition).";\n\n"
            .$this->docBlock($doc, '')
            ."final class {$definition->namespace}WebhookEvents\n{\n"
            .implode("\n\n", $constants)."\n"
            ."}\n";
    }

    private function webhookConsumer(ApiDefinition $definition, string $source): string
    {
        $events = $definition->namespace.'WebhookEvents';
        $doc = [
            \sprintf('Base consumer of the %s webhooks: extend it, override the methods of the events to handle,', $definition->namespace),
            \sprintf("and register the subclass with #[AsRemoteEventConsumer('%s')].", $definition->name),
            '',
        ];
        $handlers = [];
        $methods = [];
        foreach ($definition->webhooks['events'] as $name => $event) {
            $name = (string) $name;
            $alias = $this->payloadAlias($name);
            $method = Naming::eventMethodName($name);
            $doc[] = '@phpstan-import-type '.$alias.' from '.$events;
            $handlers[] = '        '.$events.'::'.Naming::constantName($name).' => '.$this->export($method).',';

            $methodDoc = [$this->description('"'.$name.'"'.(null !== $event['description'] ? ': '.$event['description'] : '')), '', '@param '.$alias.' $payload'];
            $methods[] = $this->docBlock($methodDoc, '    ')
                .'    protected function '.$method."(array \$payload, RemoteEvent \$event): void\n    {\n    }";
        }

        return $this->header($source)
            .'namespace '.$this->webhookNamespace($definition).";\n\n"
            ."use Snorky22\\ApiForge\\Core\\Webhook\\AbstractWebhookConsumer;\n"
            ."use Symfony\\Component\\RemoteEvent\\RemoteEvent;\n\n"
            .$this->docBlock($doc, '')
            ."abstract class Abstract{$definition->namespace}WebhookConsumer extends AbstractWebhookConsumer\n{\n"
            ."    protected const HANDLERS = [\n".implode("\n", $handlers)."\n    ];\n\n"
            .implode("\n\n", $methods)."\n"
            ."}\n";
    }

    /**
     * @param array<string, string> $imports imported resource object aliases
     */
    private function payloadType(ApiDefinition $definition, array $event, array $imports): string
    {
        if (null !== $event['shape']) {
            return trim($event['shape']);
        }
        if ('jsonapi' !== $definition->api['format']) {
            return 'array<string, mixed>';
        }

        $resource = $event['resource'] ?? null;
        $alias = null !== $resource ? Naming::aliasName($definition->resources[$resource]['type'] ?? $resource) : null;
        $data = null !== $alias && isset($imports[$alias]) ? $alias : 'array<string, mixed>';

        return "array{\n    meta: WebhookMeta,\n    data: {$data},\n}";
    }

    private function payloadAlias(string $event): string
    {
        return substr(Naming::eventMethodName($event), 2).'Payload';
    }

    private function webhookNamespace(ApiDefinition $definition): string
    {
        return $this->apiNamespace($definition).'\\Webhook';
    }

    private function apiNamespace(ApiDefinition $definition): string
    {
        return trim($this->namespace, '\\').'\\'.$definition->namespace.'\\Generated';
    }

    /**
     * A documentation text, wrapped, made safe for a docblock.
     */
    private function description(string $text): string
    {
        return wordwrap(str_replace('*/', '* /', $text), self::LINE_LENGTH - 20);
    }

    private function header(string $source): string
    {
        return "<?php\n\n// ".self::MARKER." from {$source}.\n// Do not edit: changes are lost on regeneration. Edit the descriptor instead.\n\n";
    }

    /**
     * @param list<string> $lines lines may contain line breaks (multi-line types)
     */
    private function docBlock(array $lines, string $indent): string
    {
        $block = $indent."/**\n";
        foreach ($lines as $line) {
            $block .= rtrim($indent.' * '.str_replace("\n", "\n".$indent.' * ', $line))."\n";
        }

        return $block.$indent." */\n";
    }

    /**
     * @param list<string> $parameters
     */
    private function signature(array $parameters): string
    {
        $inline = '('.implode(', ', $parameters).')';
        if (\strlen($inline) <= self::LINE_LENGTH - 40) {
            return $inline;
        }

        return "(\n".implode('', array_map(static fn (string $parameter) => '        '.$parameter.",\n", $parameters)).'    )';
    }

    /**
     * @param list<string> $arguments
     */
    private function call(string $callee, array $arguments): string
    {
        $inline = $callee.'('.implode(', ', $arguments).')';
        if (\strlen($inline) <= self::LINE_LENGTH - 15) {
            return $inline;
        }

        return $callee."(\n".implode('', array_map(static fn (string $argument) => '            '.$argument.",\n", $arguments)).'        )';
    }

    private function describe(?string $description, mixed $example, ?string $name = null): string
    {
        $parts = array_filter([
            null !== $name ? '"'.$name.'"' : null,
            $description,
            null !== $example ? 'e.g. '.json_encode($example, \JSON_UNESCAPED_SLASHES | \JSON_UNESCAPED_UNICODE) : null,
        ]);

        return implode(', ', $parts);
    }

    private function export(string $value): string
    {
        return var_export($value, true);
    }

    /**
     * @param array<string, string> $map
     */
    private function exportMap(array $map): string
    {
        $entries = [];
        foreach ($map as $key => $value) {
            $entries[] = $this->export((string) $key).' => '.$this->export($value);
        }

        return '['.implode(', ', $entries).']';
    }
}
