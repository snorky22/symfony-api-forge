<?php

namespace Snorky22\ApiForge\Tests\Dev;

use PHPUnit\Framework\TestCase;
use Snorky22\ApiForge\Dev\ConfigDeclarations;
use Symfony\Component\Filesystem\Filesystem;

final class ConfigDeclarationsTest extends TestCase
{
    private string $dir;

    protected function setUp(): void
    {
        $this->dir = sys_get_temp_dir().'/api-forge-declarations-'.bin2hex(random_bytes(4));
        $filesystem = new Filesystem();
        // Generated: a client and a webhook type of the same name
        $filesystem->dumpFile($this->dir.'/api_lemonsqueezy.yaml', "# Generated by api-forge:generate from config/api/lemonsqueezy.\nframework:\n    http_client:\n        scoped_clients:\n            lemonsqueezy.client:\n                base_uri: 'https://api.lemonsqueezy.com/v1/'\n    webhook:\n        routing:\n            lemonsqueezy:\n                service: App\\Parser\n                secret: s\n");
        // Hand-written, under when@prod, in a subdirectory
        $filesystem->dumpFile($this->dir.'/prod/paddle_client.yaml', "when@prod:\n    framework:\n        http_client:\n            scoped_clients:\n                'paddle.client': { base_uri: 'https://api.paddle.com/' }\n");
        $filesystem->dumpFile($this->dir.'/broken.yaml', "framework: [\n");
        $filesystem->dumpFile($this->dir.'/tagged.yaml', "parameters:\n    x: !php/const PHP_EOL\n");
    }

    protected function tearDown(): void
    {
        (new Filesystem())->remove($this->dir);
    }

    public function testDeclarations(): void
    {
        $declarations = new ConfigDeclarations();
        $clients = $declarations->clients($this->dir);

        self::assertSame(['lemonsqueezy.client', 'paddle.client'], array_keys($clients));
        self::assertSame([['file' => $this->dir.'/api_lemonsqueezy.yaml', 'generated' => true, 'env' => null]], $clients['lemonsqueezy.client']);
        // An environment directory and a when@ section: that environment only
        self::assertSame([['file' => $this->dir.'/prod/paddle_client.yaml', 'generated' => false, 'env' => 'prod']], $clients['paddle.client']);
        self::assertSame([], $declarations->everywhere(['paddle.client' => $clients['paddle.client']]));
        self::assertSame([], $declarations->handWrittenEverywhere(['lemonsqueezy.client' => $clients['lemonsqueezy.client']]));
        // A webhook routing key is not a client (it used to be found by a text search)
        self::assertArrayNotHasKey('lemonsqueezy', $clients);
        self::assertSame(['lemonsqueezy'], array_keys($declarations->webhooks($this->dir)));
        self::assertSame([], $declarations->clients($this->dir.'/none'));
    }

    public function testMatchingIgnoresCaseAndSeparators(): void
    {
        $declarations = new ConfigDeclarations();

        self::assertSame(['lemonsqueezy.client'], $declarations->matching($declarations->clients($this->dir), 'LemonSqueezy', '.client'));
        self::assertSame(['lemonsqueezy'], $declarations->matching($declarations->webhooks($this->dir), 'lemon_squeezy'));
        self::assertSame([], $declarations->matching($declarations->webhooks($this->dir), 'Lemon'));
    }
}
